BT_GATT_SERVICE_DEFINE(
    qnis_service,
    BT_GATT_PRIMARY_SERVICE(&qnis_service_uuid.uuid),

    /* Session-control channel: simple encrypted read/write diagnostic byte. */
    BT_GATT_CHARACTERISTIC(
        &qnis_sc_uuid.uuid,
        BT_GATT_CHRC_READ | BT_GATT_CHRC_WRITE,
        BT_GATT_PERM_READ_ENCRYPT | BT_GATT_PERM_WRITE_ENCRYPT,
        read_qnis_sc,
        write_qnis_sc,
        NULL
    ),

    /* RX: iPhone writes application messages (0x0A/0x0B/0x0C). */
    BT_GATT_CHARACTERISTIC(
        &qnis_rx_uuid.uuid,
        BT_GATT_CHRC_WRITE | BT_GATT_CHRC_WRITE_WITHOUT_RESP,
        BT_GATT_PERM_WRITE_ENCRYPT,
        NULL,
        write_qnis_rx,
        NULL
    ),

    /* TX: accessory sends notification messages to the iPhone. */
    BT_GATT_CHARACTERISTIC(
        &qnis_tx_uuid.uuid,
        BT_GATT_CHRC_NOTIFY,
        BT_GATT_PERM_NONE,
        NULL,
        NULL,
        NULL
    ),
    BT_GATT_CCC(NULL,
                BT_GATT_PERM_READ_ENCRYPT | BT_GATT_PERM_WRITE_ENCRYPT)
);

BT_GATT_SERVICE_DEFINE(
    anis_service,
    BT_GATT_PRIMARY_SERVICE(&anis_service_uuid.uuid),
    BT_GATT_CHARACTERISTIC(
        &anis_accessory_data_uuid.uuid,
        BT_GATT_CHRC_READ,
        BT_GATT_PERM_READ_ENCRYPT,
        read_anis_accessory_data,
        NULL,
        NULL
    )
);


static int qnis_notify(struct bt_conn *conn, const uint8_t *data, uint16_t len)
{
    if (conn == NULL) {
        return -ENOTCONN;
    }

    return bt_gatt_notify(conn,
                          &qnis_service.attrs[QNIS_TX_VALUE_ATTR_INDEX],
                          data, len);
}

static void config_notify_work_handler(struct k_work *work)
{
    ARG_UNUSED(work);

    if (active_conn == NULL || ni_current_state != NI_STATE_CONFIG_PENDING) {
        return;
    }

    /* The Qorvo app may enable TX notifications immediately after writing
     * 0x0A. Retry briefly so the response is not lost to that ordering race.
     */
    if (!bt_gatt_is_subscribed(active_conn,
                               &qnis_service.attrs[QNIS_TX_VALUE_ATTR_INDEX],
                               BT_GATT_CCC_NOTIFY)) {
        if (config_notify_retries++ < NI_CONFIG_NOTIFY_RETRIES) {
            k_work_reschedule(&config_notify_work,
                              K_MSEC(NI_CONFIG_NOTIFY_RETRY_MS));
        } else {
            ni_current_state = NI_STATE_IDLE;
            printk("[NI] Config response not sent: TX notifications were not enabled.\n");
        }
        return;
    }

    int ret = qnis_notify(active_conn, accessory_config_response,
                          sizeof(accessory_config_response));
    if (ret == 0) {
        ni_current_state = NI_STATE_CONFIG_SENT;
        printk("[NI] Sent Qorvo reference accessory-config response (%u bytes).\n",
               (unsigned int)sizeof(accessory_config_response));
        printk("[NI] This is a BLE test fixture, not a session-generated UWB config.\n");
    } else if (config_notify_retries++ < NI_CONFIG_NOTIFY_RETRIES) {
        printk("[NI] Config notify retry after error %d.\n", ret);
        k_work_reschedule(&config_notify_work,
                          K_MSEC(NI_CONFIG_NOTIFY_RETRY_MS));
    } else {
        ni_current_state = NI_STATE_IDLE;
        printk("[NI] Config notify failed after retries: %d\n", ret);
    }
}

K_WORK_DELAYABLE_DEFINE(config_notify_work, config_notify_work_handler);

static void uwb_test_work_handler(struct k_work *work)
{
    ARG_UNUSED(work);

    int ret = transmit_uwb_test_packet();
    uint8_t event[2] = { DBG_EVT_UWB_TX, (ret == 0) ? 1U : 0U };

    if (debug_tx_conn != NULL) {
        (void)qnis_notify(debug_tx_conn, event, sizeof(event));
        bt_conn_unref(debug_tx_conn);
        debug_tx_conn = NULL;
    }
}

K_WORK_DEFINE(uwb_test_work, uwb_test_work_handler);


/* -------------------------------------------------------------------------- */
/* GATT read/write callbacks                                                   */
