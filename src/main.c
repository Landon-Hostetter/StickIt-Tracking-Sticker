/*
 * This is the exact hand-off point where a real FiRa NI middleware stack
 * must consume Apple's shareable configuration bytes and configure the DW3110
 * (including STS, session/MAC parameters, ranging schedule, and secure ranging
 * state). The supplied low-level driver exposes radio primitives, not that
 * Apple-compatible session manager.
 *
 * Do not replace this with a guessed dwt_config_t or raw test transmission:
 * that would not implement Apple's secure NI ranging session.
 */
static int ni_start_session_from_apple_config(const uint8_t *config, size_t len)
{
    ARG_UNUSED(config);
    ARG_UNUSED(len);

    printk("[NI] Apple configuration received (%u bytes).\n",
           (unsigned int)len);
    printk("[NI] No FiRa NI middleware is present in this project.\n");
    printk("[NI] Refusing to report a false UWB session start.\n");
    return -ENOTSUP;
}

static int ni_stop_session(void)
{
    if (uwb_session_active) {
        dwt_forcetrxoff();
        uwb_session_active = false;
    }

    ni_current_state = NI_STATE_IDLE;
    apple_shareable_config_len = 0U;
    memset(apple_shareable_config, 0, sizeof(apple_shareable_config));
    return 0;
}

