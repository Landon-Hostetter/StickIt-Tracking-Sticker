static int start_advertising(void)
{
    int ret = bt_le_adv_start(BT_LE_ADV_CONN_FAST_1,
                              advertising_data,
                              ARRAY_SIZE(advertising_data),
                              scan_response,
                              ARRAY_SIZE(scan_response));
    if (ret == 0) {
        printk("[BLE] Advertising as %s\n", DEVICE_NAME);
    } else {
        printk("[BLE] Advertising start failed: %d\n", ret);
    }
    return ret;
}

static void connected(struct bt_conn *conn, uint8_t conn_err)
{
    if (conn_err != 0U) {
        printk("[BLE] Connection failed: 0x%02X\n", conn_err);
        return;
    }

    printk("[BLE] Connected. Requesting encrypted link for QNIS/ANIS.\n");

    if (active_conn != NULL) {
        bt_conn_unref(active_conn);
    }
    active_conn = bt_conn_ref(conn);

    int ret = bt_conn_set_security(conn, BT_SECURITY_L2);
    if (ret != 0) {
        printk("[BLE] Security request failed: %d\n", ret);
    }
}

static void disconnected(struct bt_conn *conn, uint8_t reason)
{
    printk("[BLE] Disconnected (reason 0x%02X).\n", reason);

    if (active_conn == conn) {
        k_work_cancel_delayable(&config_notify_work);
        active_conn = NULL;
        bt_conn_unref(conn);
    }

    /* If a test-TX work item owns a connection reference, it releases that
     * reference itself when it completes. Do not race the worker here.
     */

    (void)ni_stop_session();
    ni_current_state = NI_STATE_IDLE;

    /* Legacy connectable advertising stops while connected. Restart it. */
    (void)start_advertising();
}

static void security_changed(struct bt_conn *conn, bt_security_t level,
                             enum bt_security_err err)
{
    ARG_UNUSED(conn);
    if (err == BT_SECURITY_ERR_SUCCESS) {
        printk("[BLE] Link security established (level %u).\n",
               (unsigned int)level);
    } else {
        printk("[BLE] Link security failed (level %u, error %d).\n",
               (unsigned int)level, (int)err);
    }
}

BT_CONN_CB_DEFINE(connection_callbacks) = {
    .connected = connected,
    .disconnected = disconnected,
    .security_changed = security_changed,
};

