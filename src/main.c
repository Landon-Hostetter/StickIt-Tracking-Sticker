/*
 * DWM3001CDK Nearby Interaction protocol bring-up firmware
 *
 * This file deliberately keeps the proven DW3110 probe/configuration/test-TX
 * path from the user's working firmware, and adds:
 *   - QorvoNIService (QNIS) GATT service
 *   - Apple Nearby Interaction Service (ANIS) configuration characteristic
 *   - Apple/Qorvo NI application message framing (0x0A / 0x01 / 0x0B / 0x02 / 0x0C / 0x03)
 *   - BLE encryption request and reconnect/advertising handling
 *   - a separate QNIS session-control characteristic for local diagnostics
 *
 * IMPORTANT LIMITATION:
 * The accessory configuration bytes below are a captured Qorvo QANI reference
 * fixture, not a per-session value generated by the DWM3001 UWB middleware.
 * They are useful for exercising the BLE/GATT and message framing. The
 * proprietary Qorvo fira_niq_helper()/FiRa NI session layer is not in the
 * supplied project, so ni_start_session_from_apple_config() intentionally
 * returns -ENOTSUP. This firmware therefore DOES NOT claim that UWB ranging
 * has started and does not send the 0x02 "started" response. Do not describe
 * this build as a completed Apple NI ranging implementation.
 *
 * Message transport (as seen in Qorvo QANI logs):
 *   iPhone -> RX: 0x0A                       initialize / request config
 *   device -> TX: 0x01 + 37-byte config     accessory config response
 *   iPhone -> RX: 0x0B + Apple config       configure and start
 *   device -> TX: 0x02                       only after real UWB start succeeds
 *   iPhone -> RX: 0x0C                       stop
 *   device -> TX: 0x03                       stopped
 *
 * The static config fixture is a development aid only. Replace it with the
 * output of a real DWM3001-compatible NI/FiRa middleware implementation.
 */

