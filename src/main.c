static ssize_t read_qnis_sc(struct bt_conn *conn,
                            const struct bt_gatt_attr *attr,
                            void *buf, uint16_t len, uint16_t offset)
{
    return bt_gatt_attr_read(conn, attr, buf, len, offset,
                             &qnis_sc_value, sizeof(qnis_sc_value));
}

static ssize_t write_qnis_sc(struct bt_conn *conn,
                             const struct bt_gatt_attr *attr,
                             const void *buf, uint16_t len,
                             uint16_t offset, uint8_t flags)
{
    ARG_UNUSED(attr);
    ARG_UNUSED(flags);

    if (offset != 0U) {
        return BT_GATT_ERR(BT_ATT_ERR_INVALID_OFFSET);
    }
    if (len != 1U) {
        return BT_GATT_ERR(BT_ATT_ERR_INVALID_ATTRIBUTE_LEN);
    }

    uint8_t command = ((const uint8_t *)buf)[0];
    qnis_sc_value = command;

    printk("\n[BLE][SC] Diagnostic control 0x%02X\n", command);

    switch (command) {
    case DBG_CMD_PING: {
        uint8_t event[2] = { DBG_EVT_PING_ACK, tracker_status };
        (void)qnis_notify(conn, event, sizeof(event));
        break;
    }
    case DBG_CMD_STATUS: {
        uint8_t event[2] = { DBG_EVT_STATUS, tracker_status };
        (void)qnis_notify(conn, event, sizeof(event));
        break;
    }
    case DBG_CMD_UWB_TEST_TX:
        if (debug_tx_conn != NULL) {
            return BT_GATT_ERR(BT_ATT_ERR_INSUFFICIENT_RESOURCES);
        }
        debug_tx_conn = bt_conn_ref(conn);
        if (k_work_submit(&uwb_test_work) < 0) {
            bt_conn_unref(debug_tx_conn);
            debug_tx_conn = NULL;
            return BT_GATT_ERR(BT_ATT_ERR_UNLIKELY);
        }
        break;
    default:
        printk("[BLE][SC] Unknown diagnostic command.\n");
        break;
    }

    return len;
}

static ssize_t read_anis_accessory_data(struct bt_conn *conn,
                                        const struct bt_gatt_attr *attr,
                                        void *buf, uint16_t len,
                                        uint16_t offset)
{
    return bt_gatt_attr_read(conn, attr, buf, len, offset,
                             &accessory_config_response[1],
                             NI_CONFIG_DATA_LEN);
}

static ssize_t write_qnis_rx(struct bt_conn *conn,
                             const struct bt_gatt_attr *attr,
                             const void *buf, uint16_t len,
                             uint16_t offset, uint8_t flags)
{
    ARG_UNUSED(attr);
    ARG_UNUSED(flags);

    if (offset != 0U) {
        return BT_GATT_ERR(BT_ATT_ERR_INVALID_OFFSET);
    }
    if (len < 1U) {
        return BT_GATT_ERR(BT_ATT_ERR_INVALID_ATTRIBUTE_LEN);
    }

    const uint8_t *packet = (const uint8_t *)buf;
    const uint8_t message_id = packet[0];

    printk("\n[NI] RX write: %u bytes, message 0x%02X\n",
           (unsigned int)len, message_id);

    switch (message_id) {
    case NI_MSG_INITIALIZE:
        if (len != 1U) {
            printk("[NI] Initialize message must be exactly one byte.\n");
            return BT_GATT_ERR(BT_ATT_ERR_INVALID_ATTRIBUTE_LEN);
        }
        printk("[NI] Initialize: accessory configuration requested.\n");
        ni_current_state = NI_STATE_CONFIG_PENDING;
        config_notify_retries = 0U;
        k_work_reschedule(&config_notify_work, K_MSEC(150));
        break;

    case NI_MSG_CONFIGURE_AND_START: {
        size_t config_len = (size_t)len - 1U;

        if (config_len == 0U || config_len > sizeof(apple_shareable_config)) {
            printk("[NI] Invalid Apple shareable-config length: %u\n",
                   (unsigned int)config_len);
            return BT_GATT_ERR(BT_ATT_ERR_INVALID_ATTRIBUTE_LEN);
        }

        memcpy(apple_shareable_config, &packet[1], config_len);
        apple_shareable_config_len = config_len;
        ni_current_state = NI_STATE_APP_CONFIG_RECEIVED;

        printk("[NI] Apple shareable configuration stored unchanged (%u bytes); payload not printed.\n",
               (unsigned int)apple_shareable_config_len);

        int ret = ni_start_session_from_apple_config(
            apple_shareable_config, apple_shareable_config_len);

        if (ret == 0) {
            /* Only acknowledge 0x02 if the real UWB session actually starts. */
            uint8_t response = NI_MSG_UWB_STARTED;
            uwb_session_active = true;
            ni_current_state = NI_STATE_RUNNING;
            (void)qnis_notify(conn, &response, sizeof(response));
            printk("[NI] UWB session started.\n");
        } else {
            ni_current_state = NI_STATE_START_UNAVAILABLE;
            printk("[NI] Session not started (middleware hook returned %d).\n", ret);
        }
        break;
    }

    case NI_MSG_STOP: {
        int ret = ni_stop_session();
        if (ret == 0) {
            uint8_t response = NI_MSG_UWB_STOPPED;
            (void)qnis_notify(conn, &response, sizeof(response));
            printk("[NI] Stop handled; sent 0x03.\n");
        } else {
            printk("[NI] Stop failed: %d\n", ret);
        }
        break;
    }

    case 0xF0:
        /* Test-only extension: run the already-proven single UWB TX. */
        if (debug_tx_conn != NULL) {
            return BT_GATT_ERR(BT_ATT_ERR_INSUFFICIENT_RESOURCES);
        }
        debug_tx_conn = bt_conn_ref(conn);
        if (k_work_submit(&uwb_test_work) < 0) {
            bt_conn_unref(debug_tx_conn);
            debug_tx_conn = NULL;
            return BT_GATT_ERR(BT_ATT_ERR_UNLIKELY);
        }
        break;

    default:
        printk("[NI] Unknown RX message 0x%02X.\n", message_id);
        break;
    }

    return len;
}


