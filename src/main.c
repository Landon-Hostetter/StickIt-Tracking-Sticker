static int initialize_uwb_radio(void)
{
    printk("\n[UWB] Initializing DW3110 radio...\n");

    int ret = dwt_initialise(0);
    if (ret != DWT_SUCCESS) {
        printk("[UWB] Radio initialization failed: %d\n", ret);
        return -1;
    }

    printk("[UWB] Applying known-good channel 5 test configuration...\n");

    static dwt_config_t config = {
        .chan           = 5,
        .txPreambLength = DWT_PLEN_128,
        .rxPAC          = DWT_PAC8,
        .txCode         = 9,
        .rxCode         = 9,
        .sfdType        = DWT_SFD_IEEE_4Z,
        .dataRate       = DWT_BR_6M8,
        .phrMode        = DWT_PHRMODE_STD,
        .phrRate        = DWT_PHRRATE_STD,
        .sfdTO          = 0,
        .stsMode        = DWT_STS_MODE_OFF,
        .stsLength      = DWT_STS_LEN_64,
        .pdoaMode       = DWT_PDOA_M0
    };

    ret = dwt_configure(&config);
    if (ret != DWT_SUCCESS) {
        printk("[UWB] Radio configuration failed: %d\n", ret);
        return -2;
    }

    printk("[UWB] Test radio configuration applied.\n");
    printk("[UWB] NOTE: STS is OFF in this test profile; this is not the NI profile.\n");
    return 0;
}

static int transmit_uwb_test_packet(void)
{
    if (!uwb_ready) {
        printk("[UWB] ERROR: Radio is not ready.\n");
        return -ENODEV;
    }

    uint8_t packet[UWB_TEST_PACKET_LEN] = {
        'D', 'W', 'M', '3', '0', '0', '1'
    };

    printk("\n[UWB] Preparing known-good test transmission...\n");

    dwt_writesysstatuslo(UWB_TXFRS_MASK);

    int ret = dwt_writetxdata(sizeof(packet), packet, 0);
    if (ret != DWT_SUCCESS) {
        printk("[UWB] Failed to write TX data: %d\n", ret);
        return -EIO;
    }

    /* The DW3110 adds the two-byte PHY CRC. */
    dwt_writetxfctrl(sizeof(packet) + 2U, 0, 0);

    printk("[UWB] Starting immediate transmission...\n");
    ret = dwt_starttx(DWT_START_TX_IMMEDIATE);
    if (ret != DWT_SUCCESS) {
        printk("[UWB] Transmission could not start: %d\n", ret);
        return -EIO;
    }

    for (int i = 0; i < 100; i++) {
        if ((dwt_readsysstatuslo() & UWB_TXFRS_MASK) != 0U) {
            dwt_writesysstatuslo(UWB_TXFRS_MASK);
            printk("[UWB] SUCCESS: Test transmission completed.\n");
            return 0;
        }
        k_msleep(1);
    }

    printk("[UWB] ERROR: Test transmission timed out.\n");
    return -ETIMEDOUT;
}

