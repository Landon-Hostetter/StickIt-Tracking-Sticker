int main(void)
{
    printk("\n============================================\n");
    printk("   DWM3001 NI BLE / DW3110 BRING-UP FIRMWARE\n");
    printk("============================================\n");

    printk("\n[1] Initializing DW3110 hardware...\n");

    int ret = dw3000_hw_init();
    if (ret != 0) {
        printk("[ERROR] UWB hardware initialization: %d\n", ret);
        while (1) {
            k_sleep(K_SECONDS(2));
        }
    }

    dw3000_hw_reset();
    k_msleep(10);

    int32_t probe_result =
        dwt_probe((struct dwt_probe_s *)&dw3000_probe_interf);
    if (probe_result != DWT_SUCCESS) {
        printk("[ERROR] DW3110 identification failed.\n");
        while (1) {
            k_sleep(K_SECONDS(2));
        }
    }

    uint32_t device_id = dwt_readdevid();
    printk("[SUCCESS] DW3110 detected: 0x%08X\n", (unsigned int)device_id);

    ret = initialize_uwb_radio();
    if (ret == 0) {
        uwb_ready = true;
        tracker_status = 1U;
        printk("[SUCCESS] DW3110 test radio is ready.\n");
    } else {
        uwb_ready = false;
        tracker_status = 0U;
        printk("[WARNING] DW3110 test radio unavailable: %d\n", ret);
    }

    printk("\n[2] Initializing Bluetooth LE...\n");
    ret = bt_enable(NULL);
    if (ret != 0) {
        printk("[ERROR] Bluetooth initialization failed: %d\n", ret);
        while (1) {
            k_sleep(K_SECONDS(2));
        }
    }

    printk("[SUCCESS] Bluetooth initialized.\n");
    printk("[BLE] QNIS service: 2E938FD0-6A61-11ED-A1EB-0242AC120002\n");
    printk("[BLE] ANIS service: 48FE3E40-0817-4BB2-8633-3073689C2DBA\n");
    printk("[BLE] RX writes are encrypted; accept pairing on the iPhone.\n");

    printk("\n[3] Starting BLE advertising...\n");
    ret = start_advertising();
    if (ret != 0) {
        printk("[ERROR] BLE advertising failed: %d\n", ret);
        while (1) {
            k_sleep(K_SECONDS(2));
        }
    }

    printk("\n[NI] Supported BLE message IDs:\n");
    printk("     0x0A initialize -> 0x01 + config fixture\n");
    printk("     0x0B configure/start -> stored; UWB middleware unavailable\n");
    printk("     0x0C stop -> 0x03\n");
    printk("[DEBUG] Write 0x01/0x02/0x03 to SC for ping/status/test TX.\n");
    printk("[DEBUG] Or write 0xF0 to RX for the test TX extension.\n");
    printk("\n============================================\n");
    printk("     BLE + NI PROTOCOL BRING-UP READY\n");
    printk("============================================\n");

    while (1) {
        k_sleep(K_SECONDS(10));
    }

    return 0;
}
